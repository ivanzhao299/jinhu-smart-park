WITH seed_scope AS (
  SELECT '10000001' AS tenant_id, '20000001' AS park_id
)
INSERT INTO rel_role_perm (
  tenant_id, park_id, role_id, permission_id,
  create_time, update_time, is_deleted, version, remark
)
SELECT
  seed_scope.tenant_id,
  seed_scope.park_id,
  role.id,
  permission.id,
  now(),
  now(),
  false,
  1,
  'Repair historical core-role grants skipped before role bootstrap.'
FROM seed_scope
JOIN core_role_permission_repair role_permissions ON true
JOIN sys_role role
  ON role.tenant_id = seed_scope.tenant_id
 AND role.park_id = seed_scope.park_id
 AND role.code = role_permissions.role_code
 AND role.is_deleted = false
JOIN sys_permission permission
  ON permission.tenant_id = seed_scope.tenant_id
 AND permission.park_id = seed_scope.park_id
 AND permission.code = role_permissions.permission_code
 AND permission.is_deleted = false
WHERE NOT EXISTS (
  SELECT 1
  FROM rel_role_perm existing
  WHERE existing.tenant_id = seed_scope.tenant_id
    AND existing.park_id = seed_scope.park_id
    AND existing.role_id = role.id
    AND existing.permission_id = permission.id
    AND existing.is_deleted = false
);

DO $$
DECLARE
  missing_count integer;
BEGIN
  SELECT count(*)
  INTO missing_count
  FROM core_role_permission_repair expected
  WHERE NOT EXISTS (
    SELECT 1
    FROM sys_role role
    JOIN sys_permission permission
      ON permission.tenant_id = role.tenant_id
     AND permission.park_id = role.park_id
     AND permission.code = expected.permission_code
     AND permission.is_deleted = false
    JOIN rel_role_perm relation
      ON relation.tenant_id = role.tenant_id
     AND relation.park_id = role.park_id
     AND relation.role_id = role.id
     AND relation.permission_id = permission.id
     AND relation.is_deleted = false
    WHERE role.tenant_id = '10000001'
      AND role.park_id = '20000001'
      AND role.code = expected.role_code
      AND role.is_deleted = false
  );

  IF missing_count <> 0 THEN
    RAISE EXCEPTION
      'Core-role permission repair incomplete: % expected grants are still missing',
      missing_count;
  END IF;
END $$;

COMMIT;
