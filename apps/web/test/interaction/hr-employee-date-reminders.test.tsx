  fireEvent.click(screen.getByRole("button", { name: "预览提醒" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "生成并发送站内提醒" })).toBeEnabled());
  change("提前天数", "8"); expect(screen.getByRole("button", { name: "生成并发送站内提醒" })).toBeDisabled();
  fireEvent.click(screen.getByRole("button", { name: "预览提醒" }));
